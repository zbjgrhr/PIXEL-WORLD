/** Preserves runtime counts and model identifiers without translating project data. */
export function translateAssetDynamicText(text: string): string | undefined {
  const label = (value: string) => englishAssetUi[value] || value
  const assetList = (value: string) => value.split('、').map(item => {
    const match = item.match(/^(.*?)( 等 (\d+) 项)?$/)
    return match ? `${label(match[1])}${match[3] ? `, among ${match[3]} missing items` : ''}` : label(item)
  }).join(', ')
  const patterns: [RegExp, (...groups: string[]) => string][] = [
    [/^WebLLM 轻量补全失败，已使用本地草案：([\s\S]*)$/, detail => `WebLLM creative completion failed; a rule-based draft has been used: ${label(detail)}`],
    [/^文字模型补全失败，已使用本地草案：([\s\S]*)$/, detail => `Text-model completion failed; a rule-based draft has been used: ${label(detail)}`],
    [/^已使用 (.+) 补全设定$/, model => `Settings developed with ${model}`],
    [/^检测到 (\d+) 个 ComfyUI 检查点。$/, count => `Found ${count} ComfyUI checkpoints.`],
    [/^正在使用 (.+) 生成 (\d+) 个任务。$/, (model, count) => `Generating ${count} asset tasks with ${label(model)}.`],
    [/^动作与素材生成进度 (\d+)\/(\d+)$/, (done, total) => `Animation and asset progress: ${done}/${total}`],
    [/^缺少 (.+) 的内置动作素材。$/, title => `No built-in animation asset is available for ${label(title)}.`],
    [/^缺少 (.+) 的内置素材。$/, title => `No built-in asset is available for ${label(title)}.`],
    [/^(\d+) 个素材需要处理$/, count => `${count} assets need attention`],
    [/^(\d+)\/(\d+) 个图片任务使用内置素材或已有角色姿势补齐；模型生成的图片已保留，可继续试玩和导出。$/, (count, total) => `${count}/${total} image tasks were completed with built-in art or an existing character pose. Model-generated images have been retained. You can play and export the game.`],
    [/^已保留成功素材；(\d+) 个任务失败，可在素材卡片中重试。$/, count => `Completed assets have been retained. ${count} tasks failed and can be retried from their asset cards.`],
    [/^还缺 (.+)；可上传或点击“用内置素材补齐缺项”。$/, missing => `Still missing: ${assetList(missing)}. Upload these assets or select Fill Missing Assets with Built-in Art.`],
    [/^将重新请求 (\d+) 张图片；已有上传和生成图会被替换，并可能产生费用。$/, count => `This will request ${count} new images, replace existing uploaded and generated images, and may incur charges.`],
    [/^(.+)动作失败：([\s\S]*)$/, (pose, detail) => `${label(pose)} failed: ${label(detail)}`],
    [/^(.+)尚未生成$/, pose => `${label(pose)} has not been generated`],
    [/^已启用 (\d+) 个独立图片任务（角色按动作分别计算）；完成 (\d+) 个；待生成 (\d+) 个。(?:其中 (\d+) 个由内置素材补齐。)?程序音效和行为不调用图片 API。$/, (total, done, pending, fallback) => `${total} image tasks enabled; character actions are counted separately. Complete: ${done}; pending: ${pending}.${fallback ? ` Supplied by built-in assets: ${fallback}.` : ''} Procedural audio and behavior do not call the image API.`],
    [/^其中 (\d+) 个由内置素材补齐。$/, count => `Supplied by built-in assets: ${count}.`],
    [/^无法导出，缺少：(.+)$/, missing => `Export unavailable. Missing assets: ${assetList(missing)}`],
    [/^(\d+) 名敌人 · 完成任务后开放出口$/, count => `${count} enemies · Complete the objectives to unlock the exit`],
    [/^还需击败 (\d+) 个敌人$/, count => `Defeat ${count} more enemies`],
    [/^出口锁定：(.+)$/, reason => `Exit locked: ${translateAssetDynamicText(reason) || label(reason)}`],
  ]
  for (const [pattern, format] of patterns) {
    const match = text.match(pattern)
    if (match) return format(...match.slice(1))
  }
  return undefined
}
