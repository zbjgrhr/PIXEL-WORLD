export function translateAgentDynamicText(text: string): string | undefined {
  const narrativeRoles: Record<string, string> = { '主角': 'Protagonist', '伙伴': 'Companion', '反派': 'Antagonist', '对手': 'Opponent', '母亲': 'Mother', '妈妈': 'Mother', 'Boss': 'Boss' }
  const rules: [RegExp, (...groups: string[]) => string][] = [
    [/^Agent API 可用，锁定模型：(.+)$/, model => `Agent API available; locked model: ${model}`],
    [/^自定义文字服务可用，锁定模型：(.+)$/, model => `Custom text service available; locked model: ${model}`],
    [/^已找到 (\d+) 个本机模型。请选择一个，再测试文字模型。$/, count => `${count} local models found. Select one, then test the text model.`],
    [/^还有 (\d+) 个问题需要修改$/, count => `${count} issues require revision`],
    [/^共 (\d+) 个已启用素材、(\d+) 个关卡。批准后仍可在素材卡片中关闭项目或调整关卡分配。$/, (assets, levels) => `${assets} enabled assets and ${levels} levels. After approval, you can still disable assets or change their level assignments in the asset cards.`],
    [/^可选优化建议 (\d+) 条（不会阻止继续）$/, count => `${count} optional suggestions (you can continue without applying them)`],
    [/^保留 (\d+) 项任务成果，更新其余受影响任务时继续使用已锁定模型。$/, count => `${count} task results are retained. Updates to the remaining affected tasks use the locked model.`],
    [/^第 (\d+) 关 · (.+)$/, (level, title) => `Level ${level} · ${title}`],
    [/^线索 (\d+) · 铺垫$/, count => `Clue ${count} · Setup`],
    [/^线索 (\d+) · 回应$/, count => `Clue ${count} · Payoff`],
    [/^线索 (\d+) 出现关卡$/, count => `Level introducing clue ${count}`],
    [/^线索 (\d+) 回应关卡$/, count => `Payoff level for clue ${count}`],
    [/^内容与任务检查：(\d+) 个阻断项，(\d+) 条提醒$/, (blocking, warnings) => `Content and objective checks: ${blocking} blocking issues, ${warnings} warnings`],
    [/^内容与任务检查：程序检查通过，等待你确认内容$/, () => 'Content and objective checks: programmatic checks passed; awaiting your content review'],
    [/^(.+)(姓名|动机|人物关系)$/, (role, field) => `${narrativeRoles[role] || englishAgentUi[role] || role} · ${englishAgentUi[field]}`],
    [/^(.+) · (\d+) Token$/, (role, count) => englishAgentUi[role] ? `${englishAgentUi[role]} · ${count} tokens` : `${role} · ${count} tokens`],
  ]
  for (const [pattern, format] of rules) {
    const match = text.match(pattern)
    if (match) return format(...match.slice(1))
  }
  return undefined
}
