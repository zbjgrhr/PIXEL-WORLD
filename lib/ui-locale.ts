/** Dynamic status strings keep their counts, order, and approval conditions. */
export function translateUiText(source: string): string | undefined {
  const text = source.trim()
  if (englishUi[text]) return source.replace(text, englishUi[text])
  const agentText = translateAgentDynamicText(text)
  if (agentText) return source.replace(text, agentText)
  const assetText = translateAssetDynamicText(text)
  if (assetText) return source.replace(text, assetText)
  const patterns: [RegExp, (...groups: string[]) => string][] = [
    [/^第\s*(\d+)\s*步\s*·\s*当前操作$/, n => `Step ${n} · Current task`],
    [/^第\s*(\d+)\s*轮$/, n => `Round ${n}`],
    [/^关卡\s*(\d+)$/, n => `Level ${n}`],
    [/^·\s*待处理$/, () => '· Issues to resolve'],
    [/^已加载模板：(.+)$/, name => `Template loaded: ${englishUi[name] || name}`],
    [/^(\d+) 项改动由你决定$/, n => `${n} proposed changes require your decision`],
    [/^采用建议：(.+)$/, label => `Accept suggestion: ${englishUi[label] || label}`],
    [/^保留原文：(.+)$/, label => `Keep original: ${englishUi[label] || label}`],
    [/^查看全部 (\d+) 个图片平台$/, n => `View all ${n} image providers`],
    [/^(.+)图片类型$/, name => `Image type for ${englishUi[name] || name}`],
    [/^(.+)的(.+)动作帧条$/, (name, pose) => `${englishUi[name] || name}: ${englishUi[pose] || pose} animation strip`],
    [/^(?:(8|16|32)-bit )?(侧视)?像素风(，色彩明亮)?；角色与场景保持统一画风。$/, (bits, side, bright) => `${bits ? `${bits}-bit ` : ''}${side ? 'side-view ' : ''}pixel art${bright ? ' with bright colors' : ''}; characters and environments share a consistent visual style.`],
    [/^(.+)已应用上传图片。$/, name => `Uploaded image applied to ${englishUi[name] || name}.`],
    [/^第\s*(\d+)\s*步\s*·\s*(写故事|AI 策划|做素材)$/, (n, label) => `Step ${n} · ${englishUi[label]}`],
    [/^←\s*上一页$/, () => '← Previous'],
    [/^下一页\s*→$/, () => 'Next →'],
    [/^·\s*A\s*\/\s*D\s*翻页$/, () => '· A / D to turn pages'],
    [/^(\d+)\s*张图片$/, n => `${n} images`],
    [/^(\d+)\s*帧$/, n => `${n} frames`],
    [/^灵感与主题库\s*·\s*(.+)$/, pack => `Inspiration Library · ${englishUi[pack] || pack}`],
  ]
  for (const [pattern, format] of patterns) {
    const match = text.match(pattern)
    if (match) return source.replace(text, format(...match.slice(1)))
  }
  return undefined
}

/** Translate field headings for display; retain player-written values verbatim. */
export function localizePromptFields(source: string, locale: UiLocale): string {
  if (locale === 'zh-CN') return source
  return source.split('\n').map(line => line.replace(/^([^:：\n]+)[：:]/, (whole, label: string) => {
    const translated = translateUiText(label)
    return translated ? `${translated}:` : whole
  })).join('\n')
}

export function restorePromptFieldLabels(source: string, originalSource = ''): string {
  const labels = new Map(Object.entries(englishUi).map(([zh, en]) => [en, zh]))
  // Prefer the actual source heading when multiple Chinese labels share an English term.
  labels.set('Game title', '游戏标题')
  for (const line of originalSource.split('\n')) {
    const match = line.match(/^([^:：\n]+)[：:]/)
    if (match) {
      const translated = translateUiText(match[1])
      if (translated) labels.set(translated, match[1])
    }
  }
  return source.split('\n').map((line, index) => line.replace(/^([^:\n]+):/, (whole, label: string) => {
    const original = originalSource.split('\n')[index]?.match(/^([^:：\n]+)([：:])/)
    if (original && translateUiText(original[1]) === label) return `${original[1]}${original[2]}`
    const translated = labels.get(label)
    const level = label.match(/^Level (\d+)$/)
    return translated ? `${translated}：` : level ? `关卡 ${level[1]}：` : whole
  })).join('\n')
}
